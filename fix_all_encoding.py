    if not os.path.exists(filepath):
        print(f"???? {filepath} ?? ??????")
        return False
    
    content = read_file_safe(filepath)
    if content is None:
        return False
    
    original = content
    for old, new in replacements.items():
        content = content.replace(old, new)
    
    if content != original:
        if write_file_utf8(filepath, content):
            return True
        return False
    return False

